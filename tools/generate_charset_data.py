"""
Generate httplint/charset_data.py from the WHATWG Encoding Standard and the IANA
Character Sets registry.

Usage: PYTHONPATH=. .venv/bin/python tools/generate_charset_data.py [directory]

With a directory, reads encodings.json, indexes.json and character-sets-1.csv from it
rather than fetching them. Run `make tidy` afterwards.
"""

import csv
import io
import json
import sys
import urllib.request
from datetime import date
from pathlib import Path
from typing import Any, Dict, FrozenSet, List

ENCODINGS_URL = "https://encoding.spec.whatwg.org/encodings.json"
INDEXES_URL = "https://encoding.spec.whatwg.org/indexes.json"
IANA_URL = "https://www.iana.org/assignments/character-sets/character-sets-1.csv"
OUTPUT = Path(__file__).parent.parent / "httplint" / "charset_data.py"
REPLACEMENT_CHAR = "�"


def fetch(url: str, directory: str = "") -> str:
    if directory:
        return (Path(directory) / url.rsplit("/", 1)[-1]).read_text(encoding="utf-8")
    with urllib.request.urlopen(url, timeout=60) as response:  # nosec B310
        return str(response.read().decode("utf-8"))


def whatwg_labels(encodings: List[Dict[str, Any]]) -> Dict[str, str]:
    return {
        label: encoding["name"]
        for group in encodings
        for encoding in group["encodings"]
        for label in encoding["labels"]
    }


def single_byte_tables(
    encodings: List[Dict[str, Any]], indexes: Dict[str, Any]
) -> Dict[str, str]:
    "Bytes 0x80-0xFF as 128 characters, with U+FFFD where the index has no mapping."
    tables: Dict[str, str] = {}
    for group in encodings:
        if not group["heading"].startswith("Legacy single-byte"):
            continue
        for encoding in group["encodings"]:
            name = encoding["name"]
            # ISO-8859-8-I differs from ISO-8859-8 only in text direction.
            key = "iso-8859-8" if name == "ISO-8859-8-I" else name.lower()
            index = indexes[key]
            tables[name] = "".join(REPLACEMENT_CHAR if cp is None else chr(cp) for cp in index)
    # x-user-defined is algorithmic: 0x80-0xFF map to U+F780-U+F7FF.
    tables["x-user-defined"] = "".join(chr(0xF780 + byte - 0x80) for byte in range(0x80, 0x100))
    return tables


def iana_names(csv_text: str) -> FrozenSet[str]:
    names = set()
    for row in csv.DictReader(io.StringIO(csv_text)):
        names.add(row["Name"].lower())
        for alias in row["Aliases"].replace("\r", "").split("\n"):
            # The registry's "Aliases" cell also carries remarks, like "(aliases are
            # provided for historical reasons ...) [malyshev]".
            if alias and alias != "None" and not alias.startswith("(") and " " not in alias:
                names.add(alias.lower())
    return frozenset(names)


def main() -> int:
    directory = sys.argv[1] if len(sys.argv) > 1 else ""
    encodings = json.loads(fetch(ENCODINGS_URL, directory))
    indexes = json.loads(fetch(INDEXES_URL, directory))
    labels = whatwg_labels(encodings)
    tables = single_byte_tables(encodings, indexes)
    registered = iana_names(fetch(IANA_URL, directory))

    lines = [
        '"""',
        "Character encoding label data. GENERATED by tools/generate_charset_data.py; do",
        "not edit.",
        "",
        f"Sources, fetched {date.today().isoformat()}:",
        f"* {ENCODINGS_URL}",
        f"* {INDEXES_URL}",
        f"* {IANA_URL}",
        '"""',
        "",
        "# pylint: disable=line-too-long, too-many-lines",
        "",
        "from typing import Dict, FrozenSet",
        "",
        "# WHATWG Encoding Standard label -> encoding name.",
        f"WHATWG_LABELS: Dict[str, str] = {labels!r}",
        "",
        "# Bytes 0x80-0xFF of each single-byte encoding; U+FFFD marks an unmapped byte.",
        f"SINGLE_BYTE: Dict[str, str] = {tables!r}",
        "",
        "# Lowercased names and aliases in the IANA Character Sets registry.",
        f"IANA_NAMES: FrozenSet[str] = frozenset({sorted(registered)!r})",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(labels)} labels, {len(tables)} single-byte tables, {len(registered)} IANA names")
    return 0


if __name__ == "__main__":
    sys.exit(main())
